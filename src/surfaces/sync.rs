//! `fml sync` support: auto-generation-header detection, the generic
//! expected-vs-current file sync helper, and the tempcopy-based diff-check
//! used by in-place formatters during `fml fmt --check`.

use super::tooling::merge_tool_streams;
use super::{ExitClass, SurfaceResult, SurfaceStatus, SyncedConfigFile};
use crate::engine::diff::render_diff;
use rayon::prelude::*;
use std::path::{Path, PathBuf};
use std::time::Instant;

/// Returns true if `content` was written by `fml sync` (contains the
/// auto-generation sentinel comment). Used to guard against silently
/// overwriting hand-written configs.
#[must_use]
pub fn is_auto_generated(content: &str) -> bool {
  content.contains("DO NOT EDIT")
    || content.contains("Auto-generated by formality")
    || content.contains("WARNING: DO NOT EDIT THIS FILE DIRECTLY!")
}

/// Writes `expected_content` to `file_path` (or, with `check`, only reports
/// whether it would differ) unless the existing file was hand-edited (not
/// [`is_auto_generated`]), in which case the write is skipped to avoid
/// clobbering it.
#[must_use]
pub fn sync_file_helper(
  file_path: &Path,
  file_name: &str,
  expected_content: &str,
  check: bool,
  start: Instant,
  surface_name: &'static str,
) -> SurfaceResult {
  let exists = file_path.is_file();
  let current_content = if exists {
    std::fs::read_to_string(file_path).unwrap_or_default()
  } else {
    String::new()
  };

  if current_content.trim() == expected_content.trim() {
    return SurfaceResult {
      surface_name,
      status: SurfaceStatus::Passed,
      duration: start.elapsed(),
    };
  }

  // File exists but was not written by fml — protect it from silent overwrite.
  if exists
    && !current_content.is_empty()
    && !is_auto_generated(&current_content)
  {
    let suggestion = format!(
      "'{file_name}' exists but was not generated by formality.\n\
       It will not be overwritten automatically to avoid destroying manual settings.\n\
       \n\
       To resolve, choose one of:\n\
       \n\
       Option A — Let formality manage the file:\n\
         1. Back up your current settings.\n\
         2. Delete '{file_name}' and run 'fml sync' to generate a clean copy.\n\
         3. Migrate any custom settings you need into formality.toml using\n\
            [lang.<name>] overrides (indent_size, line_length, extra_args, …).\n\
       \n\
       Option B — Keep managing the file yourself:\n\
         Add the following header as the very first block of '{file_name}'\n\
         to suppress this warning and opt out of sync for this file:\n\
         (You will need to run 'fml sync' again after adding the header,\n\
          formality will then leave that file untouched.)\n\
       \n\
       The header that formality looks for:\n\
         # WARNING: DO NOT EDIT THIS FILE DIRECTLY!\n\
         (or the JSON equivalent: a top-level \"$comment\" containing the same text)\n\
       \n\
       Generated config for reference:\n\
       ---\n\
       {expected_content}\n\
       ---"
    );
    return SurfaceResult {
      surface_name,
      status: SurfaceStatus::ManualConfig {
        file: file_name.to_string(),
        suggestion,
      },
      duration: start.elapsed(),
    };
  }

  if check {
    let diff = render_diff(
      &current_content,
      expected_content,
      if exists { file_name } else { "(missing)" },
      &format!("{file_name} (expected)"),
    );
    SurfaceResult {
      surface_name,
      status: SurfaceStatus::ConfigDrifted {
        file: file_name.to_string(),
        diff,
      },
      duration: start.elapsed(),
    }
  } else {
    if let Some(parent) = file_path.parent() {
      let _ = std::fs::create_dir_all(parent);
    }
    match std::fs::write(file_path, expected_content) {
      Ok(()) => SurfaceResult {
        surface_name,
        status: SurfaceStatus::ConfigSynced {
          files: vec![SyncedConfigFile::new(file_name, !exists)],
        },
        duration: start.elapsed(),
      },
      Err(e) => SurfaceResult {
        surface_name,
        status: SurfaceStatus::ExecutionError {
          message: format!("Failed to write {file_name}: {e}"),
        },
        duration: start.elapsed(),
      },
    }
  }
}

/// Folds the per-file results of a surface that syncs more than one native
/// config file into the single [`SurfaceResult`] the runner renders for it.
///
/// Before #130 such a surface simply returned its *last* successful result
/// and dropped the rest, so `fml sync` could write `.markdownlint.json` and
/// then report only what prettier did — a file created on disk and named
/// nowhere in the output. Merging keeps every filename.
///
/// Semantics:
///
/// - The first non-success (drift, manual config, execution error) is
///   returned as-is. It already names the file it is about, and a surface
///   stops at its first failure rather than writing the remaining files, so
///   there is nothing further to report.
/// - Otherwise every [`SurfaceStatus::ConfigSynced`] file list is
///   concatenated in call order. If nothing was written — every file was
///   already correct — the merged status is [`SurfaceStatus::Passed`].
/// - Durations sum, so the reported time covers all the work done. Callers
///   must therefore time each file from its own [`Instant`] rather than
///   sharing one start.
///
/// # Panics
///
/// Panics on an empty slice in debug builds; a surface that syncs no file at
/// all reports [`SurfaceStatus::Skipped`] directly and never calls this.
#[must_use]
pub fn merge_sync_results(results: Vec<SurfaceResult>) -> SurfaceResult {
  debug_assert!(
    !results.is_empty(),
    "merge_sync_results called with no results"
  );
  let surface_name = results.first().map_or("", |r| r.surface_name);
  let duration = results.iter().map(|r| r.duration).sum();

  if let Some(failed) = results.iter().find(|r| !r.is_success()) {
    return SurfaceResult {
      surface_name,
      status: failed.status.clone(),
      duration,
    };
  }

  let files: Vec<SyncedConfigFile> = results
    .iter()
    .flat_map(|r| r.status.synced_files().iter().cloned())
    .collect();

  let status = if files.is_empty() {
    SurfaceStatus::Passed
  } else {
    SurfaceStatus::ConfigSynced { files }
  };

  SurfaceResult {
    surface_name,
    status,
    duration,
  }
}

enum PerFileCheckResult {
  Clean,
  Diff(String),
  /// The formatter exited non-zero. `message` already merges both captured
  /// streams; `code` is [`std::process::ExitStatus::code`] for the caller's
  /// classifier.
  FormatterError {
    message: String,
    code: Option<i32>,
  },
  ExecutionError(String),
}

/// Executes an in-place formatter on temporary copies of the given files in
/// parallel and generates unified diffs between the original content and the
/// formatted content, treating **any** non-zero formatter exit as
/// [`SurfaceStatus::ViolationsFound`].
///
/// Surfaces whose formatter distinguishes "could not run" from a formatting
/// result via its exit code should call [`diff_check_via_tempcopy_classified`]
/// so a tool *failure* is reported as [`SurfaceStatus::ExecutionError`],
/// consistently with the non-`--check` write path.
pub fn diff_check_via_tempcopy(
  files: &[PathBuf],
  run_in_place: impl Fn(&Path) -> std::io::Result<std::process::Output> + Sync,
  surface_name: &'static str,
  start: Instant,
) -> SurfaceResult {
  diff_check_via_tempcopy_classified(
    files,
    run_in_place,
    surface_name,
    start,
    |_| ExitClass::ViolationsFound,
  )
}

/// Like [`diff_check_via_tempcopy`], but lets the caller classify a non-zero
/// formatter exit code as either a formatting result or a tool failure via
/// `classify` (receives [`std::process::ExitStatus::code`], `None` on a
/// signal). On a non-zero exit both captured streams are surfaced when both
/// are non-empty — no non-empty stream is discarded.
///
/// Uses an isolated temporary directory under [`std::env::temp_dir()`] so that
/// scratch files do not pollute the workspace, and guarantees cleanup on all
/// exit paths.
// Implements temporary-file copy, in-place formatting execution, unified diff generation, and RAII cleanup across file sets.
#[allow(clippy::too_many_lines)]
pub fn diff_check_via_tempcopy_classified(
  files: &[PathBuf],
  run_in_place: impl Fn(&Path) -> std::io::Result<std::process::Output> + Sync,
  surface_name: &'static str,
  start: Instant,
  classify: impl Fn(Option<i32>) -> ExitClass,
) -> SurfaceResult {
  if files.is_empty() {
    return SurfaceResult {
      surface_name,
      status: SurfaceStatus::Passed,
      duration: start.elapsed(),
    };
  }

  let temp_dir = match tempfile::Builder::new()
    .prefix("fml-check-")
    .tempdir_in(std::env::temp_dir())
  {
    Ok(dir) => dir,
    Err(e) => {
      return SurfaceResult {
        surface_name,
        status: SurfaceStatus::ExecutionError {
          message: format!("Failed to create temporary directory: {e}"),
        },
        duration: start.elapsed(),
      };
    }
  };

  let temp_path = temp_dir.path();
  let results: Vec<PerFileCheckResult> = files
    .par_iter()
    .enumerate()
    .map(|(idx, original)| {
      let original_content = match std::fs::read_to_string(original) {
        Ok(c) => c,
        Err(e) => {
          return PerFileCheckResult::ExecutionError(format!(
            "Failed to read {}: {}",
            original.display(),
            e
          ));
        }
      };

      let file_name = original
        .file_name()
        .and_then(|n| n.to_str())
        .unwrap_or("scratch");
      let file_subfolder = temp_path.join(idx.to_string());
      if let Err(e) = std::fs::create_dir_all(&file_subfolder) {
        return PerFileCheckResult::ExecutionError(format!(
          "Failed to create temp directory {}: {}",
          file_subfolder.display(),
          e
        ));
      }
      let scratch = file_subfolder.join(file_name);

      if let Err(e) = std::fs::write(&scratch, &original_content) {
        return PerFileCheckResult::ExecutionError(format!(
          "Failed to write temp file {}: {}",
          scratch.display(),
          e
        ));
      }

      let output = match run_in_place(&scratch) {
        Ok(out) => out,
        Err(e) => {
          return PerFileCheckResult::ExecutionError(format!(
            "Failed to run formatter for {}: {}",
            original.display(),
            e
          ));
        }
      };

      if !output.status.success() {
        let stdout = String::from_utf8_lossy(&output.stdout);
        let stderr = String::from_utf8_lossy(&output.stderr);
        let message = merge_tool_streams(
          &stdout,
          &stderr,
          &format!("Formatter failed for {}", original.display()),
        );
        return PerFileCheckResult::FormatterError {
          message,
          code: output.status.code(),
        };
      }

      let formatted = match std::fs::read_to_string(&scratch) {
        Ok(f) => f,
        Err(e) => {
          return PerFileCheckResult::ExecutionError(format!(
            "Failed to read formatted temp file {}: {}",
            scratch.display(),
            e
          ));
        }
      };

      if formatted != original_content {
        let diff = render_diff(
          &original_content,
          &formatted,
          &original.display().to_string(),
          &format!("{} (formatted)", original.display()),
        );
        PerFileCheckResult::Diff(diff)
      } else {
        PerFileCheckResult::Clean
      }
    })
    .collect();

  let mut combined_diff = String::new();

  for result in results {
    match result {
      PerFileCheckResult::ExecutionError(message) => {
        return SurfaceResult {
          surface_name,
          status: SurfaceStatus::ExecutionError { message },
          duration: start.elapsed(),
        };
      }
      PerFileCheckResult::FormatterError { message, code } => {
        let status = match classify(code) {
          ExitClass::ViolationsFound => SurfaceStatus::ViolationsFound {
            message,
            diff: None,
          },
          ExitClass::ExecutionError => {
            SurfaceStatus::ExecutionError { message }
          }
        };
        return SurfaceResult {
          surface_name,
          status,
          duration: start.elapsed(),
        };
      }
      PerFileCheckResult::Diff(diff) => {
        if !combined_diff.is_empty() {
          combined_diff.push('\n');
        }
        combined_diff.push_str(&diff);
      }
      PerFileCheckResult::Clean => {}
    }
  }

  if combined_diff.is_empty() {
    SurfaceResult {
      surface_name,
      status: SurfaceStatus::Passed,
      duration: start.elapsed(),
    }
  } else {
    SurfaceResult {
      surface_name,
      status: SurfaceStatus::ViolationsFound {
        message: String::new(),
        diff: Some(combined_diff),
      },
      duration: start.elapsed(),
    }
  }
}

