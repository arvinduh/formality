  fn create_dummy_success_output() -> std::process::Output {
    #[cfg(windows)]
    {
      std::process::Command::new("cmd")
        .args(["/C", "exit 0"])
        .output()
        .expect("cmd exit 0 failed")
    }
    #[cfg(not(windows))]
    {
      std::process::Command::new("true")
        .output()
        .expect("true failed")
    }
  }

  /// A real `Output` that writes `stdout`/`stderr` (each skipped when empty)
  /// and exits with `code`, via the platform shell — so tests exercise the
  /// same `ExitStatus`/stream plumbing production does.
  fn scripted_output(
    stdout: &str,
    stderr: &str,
    code: i32,
  ) -> std::process::Output {
    #[cfg(windows)]
    {
      let mut steps: Vec<String> = Vec::new();
      if !stdout.is_empty() {
        steps.push(format!("echo {stdout}"));
      }
      if !stderr.is_empty() {
        steps.push(format!("echo {stderr} 1>&2"));
      }
      steps.push(format!("exit /b {code}"));
      std::process::Command::new("cmd")
        .arg("/C")
        .arg(steps.join(" & "))
        .output()
        .expect("scripted cmd failed")
    }
    #[cfg(not(windows))]
    {
      let mut script = String::new();
      if !stdout.is_empty() {
        script.push_str(&format!("printf '%s\\n' '{stdout}'; "));
      }
      if !stderr.is_empty() {
        script.push_str(&format!("printf '%s\\n' '{stderr}' 1>&2; "));
      }
      script.push_str(&format!("exit {code}"));
      std::process::Command::new("sh")
        .arg("-c")
        .arg(script)
        .output()
        .expect("scripted sh failed")
    }
  }

  #[test]
  fn test_is_auto_generated_recognizes_all_header_variants() {
    // is_auto_generated is the guard that decides whether fml is allowed to
    // silently overwrite an existing config file. It had zero test coverage
    // despite gating the ManualConfig-vs-ConfigSynced branch entirely.
    assert!(is_auto_generated("# DO NOT EDIT this generated file\n..."));
    assert!(is_auto_generated("// Auto-generated by formality\nfoo = 1"));
    assert!(is_auto_generated(
      "# WARNING: DO NOT EDIT THIS FILE DIRECTLY!\nfoo = 1"
    ));
    assert!(!is_auto_generated("foo = 1\nbar = 2\n"));
    assert!(!is_auto_generated(""));
  }

